CREATE TABLE DEMO_MONTHLY_REPORT AS
SELECT c.CUSTOMER_ID,
       c.CUSTOMER_SEGMENT AS SEGMENT_LABEL
FROM DEMO_CUSTOMER c;

CREATE TABLE DEMO_RISK_SEGMENTATION AS
SELECT c.CUSTOMER_ID,
       CASE
         WHEN c.CUSTOMER_SEGMENT IN ('PREMIUM', 'PRIVATE') THEN 'REVIEW'
         ELSE 'STANDARD'
       END AS RISK_BUCKET
FROM DEMO_CUSTOMER c
WHERE c.ACTIVE_FLAG = 'Y';
